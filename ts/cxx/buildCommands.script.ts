import { loadCases, Case, SUBSYSTEMS, Subsystem } from "./cases"
import { Command, CommandArgDescribed, ResponseDescribed, GGGFail } from "../ggg/Language"
import { argumentKind, enumValueNames } from "../ggg/EnumRepository"
import { resolve, dirname } from "path"
import { writeFileSync, readFileSync, existsSync, mkdirSync } from "fs"

//
// Generates the command reference (docs/commands.md) from the command metadata
// the subsystems already carry — each Command declares a `description`, an `args`
// map (arg-code -> { description, format }), and a `responds` map. Nothing here
// is hand-maintained: add a command (or an arg) in the subsystem and it shows up.
//
// Commands are grouped by subsystem (the same `needs` keys cases declare), and
// each command cross-links to the example cases that exercise it (deep links into
// docs/cases.md anchors), so the reference and the living examples stay tied.
//
// Run `npm run build:commands`, or with `--check` to verify freshness (CI).
//

const root = resolve( __dirname, "../.." )
const docsPath = resolve( root, "docs/commands.md" )

// Friendly subsystem headings (the keys match cases' `needs`).
const SUBSYSTEM_TITLES: Record<Subsystem, string> = {
  gggpx: "gggpx — print / processing",
  ggggx: "ggggx — graphics / matrix buffers",
  gggtx: "gggtx — flow control",
  gggdx: "gggdx — protocol self-description",
}

// The first whitespace-delimited token of every program line is its command code
// (e.g. `G40 R"bs" ...` -> `G40`). Collect them so we can list, per command, the
// cases that use it.
function commandsUsedBy( program: string ): Set<string> {
  const used = new Set<string>()
  for ( const line of program.split( "\n" ) ) {
    const first = line.trim().split( /\s+/ )[0]
    if ( first ) used.add( first )
  }
  return used
}

function responseText( r: ResponseDescribed ): string {
  return typeof r === "string" ? r : ( r.description ?? "" )
}

// A literal `|` breaks a markdown table cell even inside a code span, so escape it.
function cell( s: string ): string {
  return s.replace( /\|/g, "\\|" )
}

function renderArgs( args: Record<string, CommandArgDescribed> ): string {
  let s = "| code | kind | domain | format | meaning |\n| --- | --- | --- | --- | --- |\n"
  for ( const [ codeLetter, def ] of Object.entries( args ) ) {
    const fmt = def.format ? `\`${cell( def.format )}\`` : ""
    const kind = enumValueNames[argumentKind( def )]
    const domain = def.domain ? `\`${def.domain.name}\`` : ""
    s += `| \`${codeLetter}\` | \`${kind}\` | ${domain} | ${fmt} | ${cell( def.description ?? "" )} |\n`
  }
  return s + "\n"
}

// Cap the example list so high-traffic commands (P10, G10, G40) stay scannable.
const MAX_EXAMPLES = 8

function renderExamples( examples: Case[] ): string {
  if ( !examples.length ) return ""
  const shown = examples.slice( 0, MAX_EXAMPLES )
  const links = shown.map( c => `[${c.name}](cases.md#${c.name})` ).join( ", " )
  const more = examples.length > shown.length ? `, +${examples.length - shown.length} more` : ""
  return `Examples: ${links}${more}\n\n`
}

function renderCommand( code: string, def: Command, examples: Case[] ): string {
  let s = `### ${code}\n\n`
  if ( def.description ) s += `${def.description}\n\n`
  if ( def.args && Object.keys( def.args ).length ) {
    s += "Arguments:\n\n" + renderArgs( def.args )
  }
  if ( def.responds && Object.keys( def.responds ).length ) {
    s += "Responses:\n\n"
    for ( const [ rcode, r ] of Object.entries( def.responds ) ) {
      s += `- \`${rcode}\` — ${responseText( r )}\n`
    }
    s += "\n"
  }
  s += renderExamples( examples )
  return s
}

function build(): string {
  const cases = loadCases()

  let md = "# GGGCode Commands\n\n"
  md += "> AUTO-GENERATED by `ts/cxx/buildCommands.script.ts` from the subsystem command "
  md += "definitions — DO NOT EDIT.\n\n"
  md += "A command token is a letter plus a signed integer (for example `G40`, `P10`, "
  md += "or the emitted record `D-41`). The remaining tokens are code-prefixed arguments. Each "
  md += "command below links to the [cases](cases.md) that exercise it. See the "
  md += "[runtime guide](runtime.md) for how commands are dispatched and "
  md += "[glossary](glossary.md) for the argument-code vocabulary.\n\n"

  for ( const sub of Object.keys( SUBSYSTEMS ) as Subsystem[] ) {
    md += `## ${SUBSYSTEM_TITLES[ sub ] ?? sub}\n\n`
    const commands = SUBSYSTEMS[ sub ]
    const messages:Record<string,Command> = { ...commands }
    for ( const command of Object.values( commands ) ) {
      for ( const [ code, record ] of Object.entries( command.records || {} ) ) {
        messages[code] = record as Command
      }
    }
    for ( const code of Object.keys( messages ).sort() ) {
      const examples = cases.filter(
        c => c.needs.includes( sub ) && commandsUsedBy( c.program ).has( code ),
      )
      md += renderCommand( code, messages[ code ], examples )
    }
  }

  // Cross-cutting response conventions every command shares.
  md += "## Responses & failures\n\n"
  md += "Every command returns a control line. By default it is `OK` (an `O`-prefixed "
  md += "okay return); a request id set with `O<id>` is echoed back on that line. A failure "
  md += "is signalled by an `F<code>` argument on the return line, where `<code>` classifies "
  md += "the reason:\n\n"
  md += "| code | name |\n| --- | --- |\n"
  for ( const [ name, value ] of Object.entries( GGGFail ) ) {
    if ( typeof value === "number" ) md += `| \`F${value}\` | ${name} |\n`
  }
  md += "\n"

  return md
}

const content = build()

if ( process.argv.includes( "--check" ) ) {
  const current = existsSync( docsPath ) ? readFileSync( docsPath, "utf8" ) : null
  if ( current !== content ) {
    console.error( "docs/commands.md is out of date. Run `npm run build:commands`." )
    process.exit( 1 )
  }
  console.log( "Commands docs up to date." )
} else {
  mkdirSync( dirname( docsPath ), { recursive: true } )
  writeFileSync( docsPath, content )
  console.log( "Wrote docs/commands.md." )
}
