import { corpus, golden } from "./conformance"
import { resolve, dirname } from "path"
import { writeFileSync, readFileSync, existsSync, mkdirSync } from "fs"

//
// Produces the shared conformance artifacts from the TS reference:
//   - conformance/golden.json              (committed; the reference outputs)
//   - cxx/test-pio/gen/conformance_cases.h (committed; consumed by the C++ test)
//
// Run `npm run build:conformance`, or with `--check` to verify freshness (CI).
//

const root = resolve( __dirname, "../.." )
const goldenPath = resolve( root, "conformance/golden.json" )
const headerPath = resolve( root, "cxx/test-pio/gen/conformance_cases.h" )

function cEscape( s: string ): string {
  let r = ""
  for ( const ch of s ) {
    if ( ch === "\\" ) r += "\\\\"
    else if ( ch === "\"" ) r += "\\\""
    else if ( ch === "\n" ) r += "\\n"
    else if ( ch === "\r" ) r += "\\r"
    else if ( ch === "\t" ) r += "\\t"
    else r += ch
  }
  return r
}

async function build() {
  const records: { name: string, program: string, expected: string }[] = []
  for ( const c of corpus ) {
    records.push( { name: c.name, program: c.program, expected: await golden( c.program ) } )
  }

  const goldenJson = JSON.stringify( records, null, 2 ) + "\n"

  let header = "#pragma once\n"
  header += "// AUTO-GENERATED by ts/cxx/buildConformance.script.ts - DO NOT EDIT\n"
  header += "namespace ggg_conformance {\n"
  header += "  struct Case { const char* name; const char* program; const char* expected; };\n"
  header += "  constexpr Case cases[] = {\n"
  // program gets a trailing newline so the C++ parser finishes the line.
  header += records.map( r =>
    `    { "${cEscape( r.name )}", "${cEscape( r.program + "\n" )}", "${cEscape( r.expected )}" }`
  ).join( ",\n" ) + "\n"
  header += "  };\n"
  header += "  constexpr int caseCount = sizeof( cases ) / sizeof( cases[0] );\n"
  header += "}\n"

  return { [goldenPath]: goldenJson, [headerPath]: header }
}

build().then( outputs => {
  if ( process.argv.includes( "--check" ) ) {
    const stale = Object.entries( outputs ).filter( ( [ p, c ] ) =>
      ( existsSync( p ) ? readFileSync( p, "utf8" ) : null ) !== c
    )
    if ( stale.length ) {
      console.error( "Conformance artifacts out of date. Run `npm run build:conformance`. Stale files:" )
      stale.forEach( ( [ p ] ) => console.error( "  " + p ) )
      process.exit( 1 )
    }
    console.log( "Conformance artifacts up to date." )
  } else {
    for ( const [ p, c ] of Object.entries( outputs ) ) {
      mkdirSync( dirname( p ), { recursive: true } )
      writeFileSync( p, c )
    }
    console.log( `Wrote golden.json and conformance_cases.h (${corpus.length} cases).` )
  }
} )
