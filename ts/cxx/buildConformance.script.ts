import { golden } from "./conformance"
import { loadCases, decodeOutput, valuesMatch, cxxSupported, Case, EPSILON } from "./cases"
import { resolve, dirname } from "path"
import { writeFileSync, readFileSync, existsSync, mkdirSync } from "fs"

//
// Produces the shared conformance artifacts from the human-authored cases
// (cases/*.yaml, loaded by ./cases.ts):
//   - conformance/golden.json              (committed; every case + its rendered bytes)
//   - cxx/test-pio/gen/conformance_cases.h (committed; the C++-supported subset)
//
// The cross-engine contract is the DECODED `values` stream within a global epsilon
// (not raw bytes). Build-time double-entry: the TS reference output is decoded and
// must match each case's hand-authored `values` (and `status`) — a mismatch fails
// the build, so authored values cannot silently drift from the reference. Byte
// `expected` is emitted for every case in golden.json but only enforced in C++ for
// `exact` cases (where formatting itself is the test).
//
// Run `npm run build:conformance`, or with `--check` to verify freshness (CI).
//

const root = resolve( __dirname, "../.." )
const goldenPath = resolve( root, "conformance/golden.json" )
const headerPath = resolve( root, "cxx/test-pio/gen/conformance_cases.h" )

function cEscape( s: string ): string {
  let r = ""
  for ( const ch of s ) {
    if ( ch === "\\" ) r += "\\\\"
    else if ( ch === "\"" ) r += "\\\""
    else if ( ch === "\n" ) r += "\\n"
    else if ( ch === "\r" ) r += "\\r"
    else if ( ch === "\t" ) r += "\\t"
    else r += ch
  }
  return r
}

// A C++ double literal that round-trips (full precision).
function cNum( n: number ): string {
  if ( Number.isInteger( n ) ) return n.toFixed( 1 )       // 42 -> 42.0
  return n.toPrecision( 17 )
}

type GoldenRecord = {
  name: string
  description: string
  needs: string[]
  tags: string[]
  program: string
  status: string
  values: number[]
  exact: boolean
  expected: string   // rendered TS bytes (snapshot; enforced in C++ only when exact)
}

async function build() {
  const cases: Case[] = loadCases()
  const records: GoldenRecord[] = []

  for ( const c of cases ) {
    const expected = await golden( c.program, c.needs )
    // Build-time double-entry: the reference must agree with the authored ground truth.
    const { values, statuses } = decodeOutput( expected )
    if ( !valuesMatch( values, c.values ) ) {
      throw new Error(
        `case "${c.name}": authored values ${JSON.stringify( c.values )} != decoded ` +
        `reference ${JSON.stringify( values )} (epsilon ${EPSILON}) from output ${JSON.stringify( expected )}`
      )
    }
    const statusOk = c.status === ""
      ? statuses.length === 0
      : statuses.length > 0 && statuses.every( s => s === c.status )
    if ( !statusOk ) {
      throw new Error(
        `case "${c.name}": authored status ${JSON.stringify( c.status )} != decoded ` +
        `reference ${JSON.stringify( statuses )} from output ${JSON.stringify( expected )}`
      )
    }
    records.push( {
      name: c.name, description: c.description, needs: c.needs, tags: c.tags,
      program: c.program, status: c.status, values: c.values, exact: c.exact, expected,
    } )
  }

  const goldenJson = JSON.stringify( records, null, 2 ) + "\n"

  const cxxCases = cases.filter( cxxSupported )
  const excluded = cases.filter( c => !cxxSupported( c ) )
  const byName = new Map( records.map( r => [ r.name, r ] ) )

  let header = "#pragma once\n"
  header += "// AUTO-GENERATED by ts/cxx/buildConformance.script.ts - DO NOT EDIT\n"
  header += "//\n"
  header += "// Cross-engine contract: decoded `values` within EPSILON (not raw bytes).\n"
  header += "// `expected` bytes are enforced only for `exact` cases.\n"
  if ( excluded.length ) {
    header += "//\n// C++-excluded (unsatisfied subsystem `needs`):\n"
    for ( const c of excluded ) header += `//   ${c.name}: needs [${c.needs.join( ", " )}]\n`
  }
  header += "//\n"
  header += `namespace ggg_conformance {\n`
  header += `  constexpr double EPSILON = ${cNum( EPSILON )};\n`

  // Per-case value arrays (a zero-length array is ill-formed in C++, so empty
  // value sets are represented as nullptr + count 0).
  for ( const c of cxxCases ) {
    if ( c.values.length === 0 ) continue
    header += `  static const double values_${c.name}[] = { ${c.values.map( cNum ).join( ", " )} };\n`
  }

  header += "  struct Case {\n"
  header += "    const char* name; const char* program; const char* status;\n"
  header += "    const double* values; int valueCount; const char* expected;\n"
  header += "  };\n"
  header += "  constexpr Case cases[] = {\n"
  header += cxxCases.map( c => {
    const r = byName.get( c.name )!
    const valuesPtr = c.values.length === 0 ? "nullptr" : `values_${c.name}`
    const expected = c.exact ? `"${cEscape( r.expected )}"` : "nullptr"
    // program gets a trailing newline so the C++ parser finishes the line.
    return `    { "${cEscape( c.name )}", "${cEscape( c.program + "\n" )}", ` +
           `"${cEscape( c.status )}", ${valuesPtr}, ${c.values.length}, ${expected} }`
  } ).join( ",\n" ) + "\n"
  header += "  };\n"
  header += "  constexpr int caseCount = sizeof( cases ) / sizeof( cases[0] );\n"
  header += "}\n"

  return { outputs: { [goldenPath]: goldenJson, [headerPath]: header }, total: cases.length, cxxCount: cxxCases.length, excluded: excluded.length }
}

build().then( ( { outputs, total, cxxCount, excluded } ) => {
  if ( process.argv.includes( "--check" ) ) {
    const stale = Object.entries( outputs ).filter( ( [ p, c ] ) =>
      ( existsSync( p ) ? readFileSync( p, "utf8" ) : null ) !== c
    )
    if ( stale.length ) {
      console.error( "Conformance artifacts out of date. Run `npm run build:conformance`. Stale files:" )
      stale.forEach( ( [ p ] ) => console.error( "  " + p ) )
      process.exit( 1 )
    }
    console.log( "Conformance artifacts up to date." )
  } else {
    for ( const [ p, c ] of Object.entries( outputs ) ) {
      mkdirSync( dirname( p ), { recursive: true } )
      writeFileSync( p, c )
    }
    console.log( `Wrote golden.json (${total} cases) and conformance_cases.h (${cxxCount} C++ cases, ${excluded} excluded).` )
  }
} ).catch( ( err ) => {
  console.error( err.message ?? err )
  process.exit( 1 )
} )
