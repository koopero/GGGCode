import { GGG, GGGFail, CommandConvention, HexEncodings, UnitaryNames } from "../ggg/Language"
import { StorageTypes } from "../ggggx/Storage"
import Operators from "../ggggx/Operators"
import Strings from "./CxxStrings"
import { CxxMachineLimits } from "./CxxLimits"
import { resolve, dirname } from "path"
import { writeFileSync, readFileSync, existsSync, mkdirSync } from "fs"

//
// Generates C++ headers from the TypeScript source of truth.
//   - cxx/include/autogen.h          : GGG token enum + string #defines
//   - cxx/include/gen/CommandConvention.h : command-number enum
//   - cxx/include/gen/Storage.h      : storage-type descriptor table
//   - cxx/include/gen/Operators.h    : operator descriptor table (names + arity)
//
// Run `npm run build:cxx_defs` to (re)write the headers, or with `--check`
// to verify the committed headers are up to date (non-zero exit if stale).
//

const BANNER = "#pragma once\n// AUTO-GENERATED by ts/cxx/buildCxxDefs.script.ts - DO NOT EDIT\n"
const includeDir = resolve( __dirname, "../../cxx/include" )

// Emit a single-char C++ char literal, escaping as needed.
function cxxChar( code:string ) {
  switch ( code ) {
    case "\n": code = "\\n"; break
    case "\\": code = "\\\\"; break
    case "'": code = "\\'"; break
  }
  return `'${code}'`
}

function makeGGGEnum () {
  let str = "namespace ggg { typedef enum {\n"
  const done = {}
  const lines = Object.keys( GGG ).map( key => {
    let code = GGG[key]

    if ( done[code] ) {
      throw new Error( `Duplicate code: ${code}` )
    }
    done[code] = true
    let str = ""

    if ( code.length == 1 ) {
      switch ( code ) {
        case "\n": code = "\\n"; break
        case "\\": code = "\\\\"; break
      }

      str += `  ${key} = '${code}'`
    }

    return str
  } )
  str += `${lines.join( ",\n" )}\n`
  str += "} GGG; };\n\n"
  return str
}

function makeStringDefines() {
  let str = "// Strings\n"
  for ( const key in Strings ) {
    const value = Strings[key]
    str += `#define ${key} "${value}"\n`
  }
  return str
}

// Hex encoding codes (HexEncodings in TS). These were moved out of the GGG
// enum but the parser still needs them, so generate a sibling plain enum.
function makeHexEncodings() {
  let str = "namespace ggg { typedef enum {\n"
  const lines = Object.keys( HexEncodings ).map( key => `  ${key} = ${cxxChar( HexEncodings[key] )}` )
  str += lines.join( ",\n" ) + "\n"
  str += "} HexEncodings; };\n\n"
  return str
}

// Encoded unitary output codes. EncodedOne stays in the GGG enum; Zero and
// MinusOne live in UnitaryNames (Language.ts), so emit them as constants.
function makeEncodedUnitary() {
  let str = "namespace ggg {\n"
  str += `  constexpr char EncodedZero = ${cxxChar( UnitaryNames.Zero )};\n`
  str += `  constexpr char EncodedMinusOne = ${cxxChar( UnitaryNames.MinusOne )};\n`
  str += "};\n\n"
  return str
}

// Failure codes (Language.ts GGGFail) carried by the F<code> arg on a return.
// Numeric TS enums carry a reverse map (value -> name); keep only the forward
// (name -> value) entries.
function makeFailCodes() {
  const entries = Object.entries( GGGFail )
    .filter( ( [ key ] ) => isNaN( Number( key ) ) ) as [ string, number ][]
  let str = "namespace ggg { enum class GGGFail : int {\n"
  str += entries.map( ( [ key, value ] ) => `  ${key} = ${value}` ).join( ",\n" ) + "\n"
  str += "}; };\n\n"
  return str
}

function emitAutogen() {
  return BANNER + makeGGGEnum() + makeHexEncodings() + makeEncodedUnitary() + makeFailCodes() + makeStringDefines()
}

// Command numbers (Language.ts CommandConvention). Numeric TS enums carry a
// reverse map (value -> name); keep only the forward (name -> value) entries.
function emitCommandConvention() {
  const entries = Object.entries( CommandConvention )
    .filter( ( [ key ] ) => isNaN( Number( key ) ) ) as [ string, number ][]

  let str = BANNER
  str += "namespace ggg {\n"
  str += "  enum class CommandConvention : int {\n"
  str += entries.map( ( [ key, value ] ) => `    ${key} = ${value}` ).join( ",\n" ) + "\n"
  str += "  };\n"
  str += "}\n"
  return str
}

// Storage-type descriptors (Storage.ts). The `cxxStorage` field already names
// the backing C++ type for each storage type.
function emitStorage() {
  let str = BANNER
  str += "#include \"../Types.h\"\n\n"
  str += "namespace ggg {\n"
  str += "  struct StorageDescriptor {\n"
  str += "    Index index;\n"
  str += "    const char* name;\n"
  str += "    NumberType norm1;\n"
  str += "    bool hasRange;\n"
  str += "    NumberType rangeMin;\n"
  str += "    NumberType rangeMax;\n"
  str += "    char encoding;\n"
  str += "    const char* cxxStorage;\n"
  str += "  };\n\n"
  str += "  constexpr StorageDescriptor StorageDescriptors[] = {\n"
  const rows = StorageTypes.list.filter( Boolean ).map( s => {
    const hasRange = !!s.range
    const min = s.range ? s.range[0] : 0
    const max = s.range ? s.range[1] : 0
    const enc = ( typeof s.encoding === "string" && s.encoding.length === 1 ) ? cxxChar( s.encoding ) : "0"
    return `    { ${s.index}, "${s.name}", ${s.norm1}, ${hasRange}, ${min}, ${max}, ${enc}, "${s.cxxStorage}" }`
  } )
  str += rows.join( ",\n" ) + "\n"
  str += "  };\n"
  str += "  constexpr Index StorageDescriptorCount = sizeof( StorageDescriptors ) / sizeof( StorageDescriptors[0] );\n"
  str += "}\n"
  return str
}

// Operator descriptors (Operators.ts). Names are emitted as strings (not an
// enum) because several operator names (and, or, xor, not, bool) are C++
// keywords. The operator math itself is hand-written in C++; this table only
// locks the name/index/arity set so the two implementations agree.
function emitOperators() {
  let str = BANNER
  str += "#include \"../Types.h\"\n\n"
  str += "namespace ggg {\n"
  str += "  struct OperatorDescriptor {\n"
  str += "    Index index;\n"
  str += "    const char* name;\n"
  str += "    Index args;\n"
  str += "  };\n\n"
  str += "  constexpr OperatorDescriptor OperatorDescriptors[] = {\n"
  const rows = Operators.list.filter( Boolean ).map( o =>
    `    { ${o.index}, "${o.name}", ${o.args} }`
  )
  str += rows.join( ",\n" ) + "\n"
  str += "  };\n"
  str += "  constexpr Index OperatorDescriptorCount = sizeof( OperatorDescriptors ) / sizeof( OperatorDescriptors[0] );\n"
  str += "}\n"
  return str
}

// Machine limits (cxx/include/ggg/Limits.h) from the TS source of truth.
function emitLimits() {
  let str = BANNER
  str += "#include \"../Types.h\"\n\n"
  str += "namespace ggg {\n"
  str += "  struct MachineLimits {\n"
  for ( const [ key, value ] of Object.entries( CxxMachineLimits ) ) {
    str += `    Index ${key} = ${value};\n`
  }
  str += "  };\n"
  str += "}\n"
  return str
}

const outputs: { [path:string]:string } = {
  [resolve( includeDir, "autogen.h" )]: emitAutogen(),
  [resolve( includeDir, "gen/CommandConvention.h" )]: emitCommandConvention(),
  [resolve( includeDir, "gen/Storage.h" )]: emitStorage(),
  [resolve( includeDir, "gen/Operators.h" )]: emitOperators(),
  [resolve( includeDir, "ggg/Limits.h" )]: emitLimits(),
}

if ( process.argv.includes( "--check" ) ) {
  const stale = Object.entries( outputs ).filter( ( [ path, content ] ) =>
    ( existsSync( path ) ? readFileSync( path, "utf8" ) : null ) !== content
  )
  if ( stale.length ) {
    console.error( "C++ codegen is out of date. Run `npm run build:cxx_defs`. Stale files:" )
    stale.forEach( ( [ path ] ) => console.error( "  " + path ) )
    process.exit( 1 )
  }
  console.log( "C++ codegen is up to date." )
} else {
  for ( const [ path, content ] of Object.entries( outputs ) ) {
    mkdirSync( dirname( path ), { recursive: true } )
    writeFileSync( path, content )
  }
  console.log( `Generated ${Object.keys( outputs ).length} C++ header(s).` )
}
