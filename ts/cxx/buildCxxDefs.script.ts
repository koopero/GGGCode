import { GGG } from "../ggg/gggLang"
import Strings from "./CxxStrings"
import { resolve } from "path"
import { writeFileSync, existsSync } from "fs"

let str = `#pragma once\n// Auto-generated by ts/cxx/makeCxxDefs.ts\n`

function makeGGGEnum () {
  let str = `namespace ggg { typedef enum {\n`
  const type = "gggChar"
  const done = {}
  const lines = Object.keys( GGG ).map( key => {
    let code = GGG[key]

    if ( done[code] ) {
      throw new Error( `Duplicate code: ${code}` )
    }
    done[code] = true
    let str = ''
    
    if ( code.length == 1 ) {
      switch ( code ) {
        case "\n": code = "\\n"; break
        case "\\": code = "\\\\"; break
      }

      str += `  ${key} = '${code}'`
    }

    return str
  } )
  str += `${lines.join( ",\n" )}\n`
  str += `} GGG; };\n\n`
  return str
}

function makeStringDefines() {
  let str = `// Strings\n`
  for ( let key in Strings ) {
    let value = Strings[key]
    str += `#define ${key} "${value}"\n`
  }
  return str
}

str += makeGGGEnum()
str += makeStringDefines()


const path = resolve( __dirname, "../../cxx/include/autogen.h" )
writeFileSync( path, str )